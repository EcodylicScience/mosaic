"""Regenerate `docs/reference/` from the registries the running code holds.

Five pages are generated whole from five authorities: `FEATURES`, `OPS`,
`MEDIA_STEPS`, the two converter registries beside `TRACK_SCHEMAS`, and the Typer app
behind the `mosaic` console script. Each is already the authority at run time, and
the CLI's discovery commands read these same registries. A reference page derived
from anything else is a second answer, and second answers drift.

They had drifted. Three hand-maintained feature lists disagreed with each other
and all three with the registry: the site's landing page said "~30", the feature
library page said "40+" and listed 28, the README listed a subset, and `FEATURES`
held 44. Twelve features appeared in none of them.

**Why the output is committed rather than produced during `mkdocs build`.**
`FEATURES` is filled by import side effects in
`behavior/feature_library/__init__.py`, so the registry is exactly as complete as
the environment that imported it. A generator running inside the build, in an
environment missing one dependency, emits a *shorter* list -- and `mkdocs build
--strict` still reports success, because a feature that never registered raises
no warning. Nothing about the page would look wrong. Diffing against a committed
file turns that silence into a failed job that names what went missing, and it
puts the docs change in the same review as the code change that caused it.

**Why a reduced parameter table rather than the raw schema.** The JSON-Schema
document moves whenever pydantic changes how it spells a union or where it hangs
a constraint, and every such move would fail `--check` on an unrelated pull
request. Name, type, default and constraints absorb that. The description is
mosaic's own text, published by `Declared` and by nothing else -- the `Field`
spelling is refused -- so it moves when an author changes it and at no other
time.

Writes nothing by default, like `gen_third_party_inventory.py` beside it.
`--check` regenerates in memory and prints a unified diff of whatever no longer
matches, which is what CI runs; `--write` is the one mode that touches the tree.

No timestamp, no tool version and no package version appears in the output.
Any of them would make every regeneration a diff, which is the fastest way to
teach people to skip the check.
"""

