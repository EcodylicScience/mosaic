def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="Regenerate in memory and diff against what is committed (default).",
    )
    mode.add_argument(
        "--write", action="store_true", help="Write the pages to docs/reference/."
    )
    parser.add_argument(
        "--page",
        choices=sorted(PAGES),
        action="append",
        help="Limit to one page (repeatable).",
    )
    args = parser.parse_args()

    selected = args.page or sorted(PAGES)
    if args.write:
        REFERENCE_ROOT.mkdir(parents=True, exist_ok=True)

    stale: list[str] = []
    for name in selected:
        rendered = PAGES[name]()
        path = REFERENCE_ROOT / f"{name}.md"
        if args.write:
            path.write_text(rendered, encoding="utf-8")
            continue
        committed = path.read_text(encoding="utf-8") if path.exists() else ""
        if committed == rendered:
            continue
        stale.append(name)
        sys.stdout.writelines(
            difflib.unified_diff(
                committed.splitlines(keepends=True),
                rendered.splitlines(keepends=True),
                fromfile=f"{path.relative_to(REPOSITORY_ROOT)} (committed)",
                tofile=f"{path.relative_to(REPOSITORY_ROOT)} (regenerated)",
            )
        )

    if args.write:
        print(
            f"Wrote {len(selected)} page(s) to {REFERENCE_ROOT.relative_to(REPOSITORY_ROOT)}/"
        )
        return 0
    if stale:
        print(
            f"\n{len(stale)} generated page(s) out of date: {', '.join(stale)}.\n"
            "Run `python scripts/gen_docs_reference.py --write` and commit the result.",
            file=sys.stderr,
        )
        return 1
    print(f"{len(selected)} generated page(s) up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
